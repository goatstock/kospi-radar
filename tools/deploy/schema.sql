CREATE TABLE IF NOT EXISTS u(id INTEGER PRIMARY KEY AUTOINCREMENT, email TEXT UNIQUE, salt TEXT, h TEXT, role TEXT DEFAULT 'trial', created INTEGER, trial_end INTEGER, last INTEGER);
CREATE TABLE IF NOT EXISTS s(tok TEXT PRIMARY KEY, uid INTEGER, exp INTEGER, ua TEXT);
CREATE TABLE IF NOT EXISTS rl(k TEXT PRIMARY KEY, n INTEGER, exp INTEGER);
CREATE TABLE IF NOT EXISTS us(uid INTEGER, day TEXT, n INTEGER, PRIMARY KEY(uid,day));
